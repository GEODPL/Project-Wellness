def main():
    print(f"Θα εισαχθούν {len(KNOWLEDGE_BASE)} εγγραφές στη βάση γνώσης...\n")

    for i, entry in enumerate(KNOWLEDGE_BASE, start=1):
        embedding = model.encode(entry["content"]).tolist()
        supabase.table("reframe_knowledge").insert(
            {
                "distortion_type": entry["distortion_type"],
                "content": entry["content"],
                "embedding": embedding,
            }
        ).execute()
        preview = entry["content"][:55].replace("\n", " ")
        print(f"  [{i}/{len(KNOWLEDGE_BASE)}] ✓ {entry['distortion_type']}: {preview}...")

    print("\n✅ Ολοκληρώθηκε! Η βιβλιοθήκη γνώσης είναι έτοιμη στη Supabase.")


if __name__ == "__main__":
    main()